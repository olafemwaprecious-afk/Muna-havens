#!/usr/bin/env node
/**
 * Muna's Haven build step — deliberately tiny.
 *
 * There is no bundler, transpiler or framework here. The only thing that must
 * happen before publishing is that `assets/js/config.js` is generated from
 * environment variables, so the Supabase project reference and publishable key
 * never enter git history. This site is published as plain files.
 *
 *   npm run build          -> writes assets/js/config.js for local preview
 *   npm run build -- --site -> also writes _site/ for the Pages action
 */
import { readFile, writeFile, mkdir, rm, cp, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const wantSiteDir = process.argv.includes('--site');
const siteDir = path.join(root, '_site');

const KEYS = ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'PUBLIC_SITE_URL', 'MUNA_REALTIME'];

async function loadEnvFile() {
  const values = {};
  try {
    const raw = await readFile(path.join(root, '.env'), 'utf8');
    for (const line of raw.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq < 1) continue;
      const key = trimmed.slice(0, eq).trim();
      let value = trimmed.slice(eq + 1).trim();
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }
      values[key] = value;
    }
  } catch {
    /* no .env file — that is a valid state (demo mode) */
  }
  return values;
}

function pick(name, fileValues) {
  const fromEnv = process.env[name];
  if (fromEnv && fromEnv.trim()) return fromEnv.trim();
  const fromFile = fileValues[name];
  if (fromFile && fromFile.trim()) return fromFile.trim();
  return '';
}

/** Refuse to publish a privileged credential even if one was pasted by mistake. */
function assertPublicOnly(name, value) {
  const patterns = [
    { re: /\bsb_secret_/i, why: 'a Supabase secret (service_role) key' },
    { re: /service_role/i, why: 'a service_role token' },
    { re: /\beyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b/, why: 'a JWT that may be a privileged token' },
    { re: /^postgres(ql)?:\/\//i, why: 'a database connection string' },
  ];
  for (const { re, why } of patterns) {
    if (re.test(value)) {
      throw new Error(
        `Refusing to write ${name}: it looks like ${why}. Only the project URL and the ` +
          `publishable (anon) key belong in frontend files.`,
      );
    }
  }
}

/** A value interpolated into a JS string literal must not be able to escape it. */
function safeJson(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function renderConfig(values) {
  return `/* GENERATED by scripts/build.mjs — do not edit and do not commit.
 * Source of truth: .env (local) or GitHub repository variables (deploy).
 * Both values below are PUBLIC browser configuration; access control is
 * enforced by Row Level Security in PostgreSQL, not by hiding these.
 */
window.MUNA_HAVEN_CONFIG = {
  supabaseUrl: ${safeJson(values.supabaseUrl)},
  supabaseAnonKey: ${safeJson(values.anonKey)},
  siteUrl: ${safeJson(values.siteUrl)},
  realtime: ${values.realtime === '1' || values.realtime === 'true'},
  generatedAt: ${safeJson(new Date().toISOString())},
};
`;
}

async function exists(file) {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}

const fileValues = await loadEnvFile();
const values = {
  supabaseUrl: pick('SUPABASE_URL', fileValues),
  anonKey: pick('SUPABASE_ANON_KEY', fileValues),
  siteUrl: pick('PUBLIC_SITE_URL', fileValues),
  realtime: pick('MUNA_REALTIME', fileValues),
};

assertPublicOnly('SUPABASE_ANON_KEY', values.anonKey);
assertPublicOnly('SUPABASE_URL', values.supabaseUrl);
assertPublicOnly('PUBLIC_SITE_URL', values.siteUrl);

if (values.supabaseUrl && !values.anonKey) {
  console.warn('! SUPABASE_URL is set but SUPABASE_ANON_KEY is not — the app will fall back to demo data.');
}
if (values.supabaseUrl && !/^https:\/\//i.test(values.supabaseUrl)) {
  throw new Error('SUPABASE_URL must start with https:// (http is only allowed for a local emulator).');
}

const configPath = path.join(root, 'assets/js/config.js');
await writeFile(configPath, renderConfig(values), 'utf8');
const configured = Boolean(values.supabaseUrl && values.anonKey);
console.log(
  configured
    ? `✓ assets/js/config.js → live Supabase project (${values.supabaseUrl.replace(/^https?:\/\//, '')})`
    : '✓ assets/js/config.js → no credentials found, the site will run in labelled demo mode',
);

if (wantSiteDir) {
  await rm(siteDir, { recursive: true, force: true });
  await mkdir(siteDir, { recursive: true });
  const publish = ['index.html', '404.html', 'owner', 'tools', 'assets', 'robots.txt', 'site.webmanifest'];
  for (const entry of publish) {
    const from = path.join(root, entry);
    if (await exists(from)) await cp(from, path.join(siteDir, entry), { recursive: true });
  }
  await writeFile(configPath, renderConfig(values), 'utf8');
  console.log('✓ _site/ assembled for GitHub Pages upload');
}
